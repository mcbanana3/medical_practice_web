CREATE TABLE IF NOT EXISTS public_review_submissions (
  id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
  submission_key CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  payload_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  location_id INT UNSIGNED NOT NULL,
  provider_id INT UNSIGNED NOT NULL,
  status ENUM('pending','approved','rejected','withdrawn') NOT NULL DEFAULT 'pending',
  version INT UNSIGNED NOT NULL DEFAULT 1,
  submission_enc MEDIUMTEXT NOT NULL,
  publication_consent BOOLEAN NOT NULL,
  withdraw_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  public_json JSON NULL,
  checks_json JSON NULL,
  internal_note_enc TEXT NULL,
  moderated_by VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL,
  approved_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL,
  updated_at DATETIME(3) NOT NULL,
  UNIQUE KEY public_review_submission(submission_key),
  UNIQUE KEY public_review_withdrawal(withdraw_hash),
  KEY public_review_queue(location_id,provider_id,status,created_at),
  KEY public_review_published(status,approved_at,id),
  FOREIGN KEY(location_id) REFERENCES locations(id),
  FOREIGN KEY(provider_id) REFERENCES providers(id),
  FOREIGN KEY(moderated_by) REFERENCES staff_users(subject)
) ENGINE=InnoDB;